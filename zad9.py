# Просим пользователя ввести границы отрезка и шаг
a = float(input("Начало отрезка (a): "))  # float — чтобы можно было вводить дробные (0.5)
b = float(input("Конец отрезка (b): "))
h = float(input("Шаг (h): "))

# Печатаем заголовок таблицы
print("x\t\ty = x^2")   # \t — это табуляция (отступ)
print("-" * 20)          # черта из 20 минусов для красоты

# Начинаем с левой границы отрезка
x = a

# Пока x не вышел за правую границу — крутим цикл
while x <= b:
    y = x * x            # считаем квадрат x
    
    # Выводим x и y, округляя до 2 знаков после запятой
    print(round(x, 2), "\t", round(y, 2))
    
    x = x + h            # сдвигаем x на шаг h, иначе цикл зациклится